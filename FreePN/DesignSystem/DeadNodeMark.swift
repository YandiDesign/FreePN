    public func path(in rect: CGRect) -> Path {
        let unit = rect.width / Self.box
        func map(_ pt: CGPoint) -> CGPoint {
            CGPoint(x: rect.minX + pt.x * unit, y: rect.minY + pt.y * unit)
        }
        var path = Path()
        for segment in Self.outline {
            switch segment {
            case .move(let pt):
                path.move(to: map(pt))
            case .line(let pt):
                path.addLine(to: map(pt))
            case .arc(let center, let radius, let start, let end, let clockwise):
                path.addArc(center: map(center), radius: radius * unit,
                            startAngle: .degrees(start), endAngle: .degrees(end),
                            clockwise: clockwise)
            case .close:
                path.closeSubpath()
            }
        }
        return path
    }

    /// Kotak pembatas glyph dalam koordinat viewBox — dipakai test.
    public static var sourceBounds: CGRect {
        var minX = CGFloat.greatestFiniteMagnitude, minY = CGFloat.greatestFiniteMagnitude
        var maxX = -CGFloat.greatestFiniteMagnitude, maxY = -CGFloat.greatestFiniteMagnitude
        func note(_ pt: CGPoint) {
            minX = min(minX, pt.x); maxX = max(maxX, pt.x)
            minY = min(minY, pt.y); maxY = max(maxY, pt.y)
        }
        for segment in outline {
            switch segment {
            case .move(let pt), .line(let pt): note(pt)
            case .arc(let c, _, _, _, _): note(c)
            case .close: break
            }
        }
        return CGRect(x: minX, y: minY, width: maxX - minX, height: maxY - minY)
    }
